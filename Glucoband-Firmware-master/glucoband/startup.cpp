void playStartupAnimation(Adafruit_SSD1306& display) {
  for (int i = 0; i < FRAME_COUNT; i++) {
    display.clearDisplay();
    display.drawBitmap(0, 0, FRAMES[i], 128, 64, SSD1306_WHITE);
    display.display();
    if (i == 13) {
      delay(2000);
    } else {
      delay(50);
    }
  }
  display.clearDisplay();
  display.display();
}
void playJari(Adafruit_SSD1306& display) {
  for (int i = 0; i < 4; i++) {
    display.fillRect(0, 18, 128, 26, SSD1306_BLACK);
    display.drawBitmap(0, 18, gallArray[i], 128, 26, SSD1306_WHITE);
    display.display();
    vTaskDelay(pdMS_TO_TICKS(100));
  }
}
